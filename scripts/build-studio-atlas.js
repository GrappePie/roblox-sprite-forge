import fs from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import sharp from "sharp";

const DIRECTIONS = [
  "down",
  "down_left",
  "left",
  "up_left",
  "up",
  "up_right",
  "right",
  "down_right",
];
const LEGACY_CLIPS = ["idle", "walk", "run", "jump", "fall", "climb"];

const sourceDirectory = path.resolve(
  process.argv[2] ?? "data/generated/215dae25-0c0a-4614-9508-682dc7948570",
);
const outputDirectory = path.resolve(process.argv[3] ?? "studio-prototype/generated");

const manifest = JSON.parse(await fs.readFile(path.join(sourceDirectory, "manifest.json"), "utf8"));
const sheetPath = path.join(sourceDirectory, manifest.sheet.image ?? "sheet.png");
const { data, info } = await sharp(sheetPath)
  .ensureAlpha()
  .raw()
  .toBuffer({ resolveWithObject: true });

const frameWidth = Number(manifest.sheet.frameWidth);
const frameHeight = Number(manifest.sheet.frameHeight);
const columns = Number(manifest.sheet.columns);
const rows = Number(manifest.sheet.rows);
const clips = Array.isArray(manifest.settings?.clips) && manifest.settings.clips.length
  ? manifest.settings.clips.map(String)
  : LEGACY_CLIPS;
const framesPerAnimation = Number(manifest.settings.framesPerAnimation);
const clipFrameCounts = Object.fromEntries(clips.map((clip) => [
  clip,
  Number(manifest.settings?.frameCounts?.[clip] ?? framesPerAnimation),
]));

if (info.width !== frameWidth * columns || info.height !== frameHeight * rows) {
  throw new Error(`Atlas dimensions do not match its manifest: ${info.width}x${info.height}.`);
}

const palette = [];
const paletteLookup = new Map();
const pixelIndexes = new Uint8Array(info.width * info.height);

for (let pixel = 0, offset = 0; offset < data.length; pixel += 1, offset += 4) {
  const key = data.readUInt32BE(offset);
  let paletteIndex = paletteLookup.get(key);
  if (paletteIndex === undefined) {
    paletteIndex = palette.length;
    paletteLookup.set(key, paletteIndex);
    palette.push([data[offset], data[offset + 1], data[offset + 2], data[offset + 3]]);
  }
  pixelIndexes[pixel] = paletteIndex;
}

if (palette.length > 16) {
  throw new Error(`Studio's compact 12-bit RLE supports 16 colors; this sheet has ${palette.length}.`);
}

await fs.mkdir(outputDirectory, { recursive: true });
const chunks = [];
let packedBytes = 0;

for (let row = 0; row < rows; row += 1) {
  const start = row * frameHeight * info.width;
  const end = start + frameHeight * info.width;
  const words = [];
  let cursor = start;

  while (cursor < end) {
    const paletteIndex = pixelIndexes[cursor];
    let runLength = 1;
    while (
      cursor + runLength < end
      && pixelIndexes[cursor + runLength] === paletteIndex
      && runLength < 4095
    ) {
      runLength += 1;
    }
    words.push((runLength << 4) | paletteIndex);
    cursor += runLength;
  }

  const packed = Buffer.allocUnsafe(words.length * 2);
  words.forEach((word, index) => packed.writeUInt16LE(word, index * 2));
  packedBytes += packed.length;
  const base64Lines = packed.toString("base64").match(/.{1,120}/g) ?? [];
  const chunkName = `Row${String(row).padStart(2, "0")}`;
  chunks.push(chunkName);
  await fs.writeFile(
    path.join(outputDirectory, `${chunkName}.lua`),
    `-- Generated by scripts/build-studio-atlas.js. Do not edit by hand.\nreturn [[\n${base64Lines.join("\n")}\n]]\n`,
  );
}

const paletteSource = palette
  .map((color) => `\t\t{ ${color.join(", ")} },`)
  .join("\n");
const chunkSource = chunks.map((name) => `\t\t"${name}",`).join("\n");
const directionRows = DIRECTIONS.map((name, index) => `\t\t${name} = ${index},`).join("\n");
const clipRows = clips.map((name, index) => `\t\t${name} = ${index},`).join("\n");
const clipFrameCountSource = clips
  .map((name) => `\t\t${name} = ${clipFrameCounts[name]},`)
  .join("\n");

const metadataSource = `--!strict
-- Generated by scripts/build-studio-atlas.js. Do not edit by hand.
return {
\tVersion = 1,
\tUserId = ${Number(manifest.source.userId)},
\tUsername = ${JSON.stringify(manifest.source.username)},
\tJobId = ${JSON.stringify(path.basename(sourceDirectory))},
\tWidth = ${info.width},
\tHeight = ${info.height},
\tFrameWidth = ${frameWidth},
\tFrameHeight = ${frameHeight},
\tColumns = ${columns},
\tRows = ${rows},
\tFramesPerAnimation = ${framesPerAnimation},
\tClipFrameCounts = {
${clipFrameCountSource}
\t},
\tIdleFps = ${clipFrameCounts.idle / 4},
\tIdleAltFps = ${(clipFrameCounts.idle_alt ?? clipFrameCounts.idle) / 4},
\tWalkFps = 10,
\tRunFps = 14,
\tJumpFps = 11,
\tFallFps = 11,
\tClimbFps = 10,
\tRunSpeedThreshold = 18,
\tDirectionRows = {
${directionRows}
\t},
\tClipRows = {
${clipRows}
\t},
\tClipCount = ${clips.length},
\tPalette = {
${paletteSource}
\t},
\tChunks = {
${chunkSource}
\t},
}
`;

await fs.writeFile(path.join(outputDirectory, "AtlasMetadata.lua"), metadataSource);
await fs.writeFile(
  path.join(outputDirectory, "atlas-build.json"),
  `${JSON.stringify({
    sourceDirectory,
    userId: manifest.source.userId,
    username: manifest.source.username,
    width: info.width,
    height: info.height,
    colors: palette.length,
    chunks: chunks.length,
    packedBytes,
  }, null, 2)}\n`,
);

console.log(JSON.stringify({
  outputDirectory,
  userId: manifest.source.userId,
  size: `${info.width}x${info.height}`,
  colors: palette.length,
  chunks: chunks.length,
  packedBytes,
}));
